func TestLoadPacks(t *testing.T) {
	packs, err := level.LoadPacks()
	if err != nil {
		t.Fatal(err)
	}
	entries, err := assets.LevelFiles.ReadDir("levels")
	if err != nil {
		t.Fatal(err)
	}
	expected := 0
	for _, entry := range entries {
		if !entry.IsDir() && (strings.EqualFold(filepath.Ext(entry.Name()), ".xsb") || strings.EqualFold(filepath.Ext(entry.Name()), ".txt")) {
			expected++
		}
	}
	if len(packs) != expected {
		t.Fatalf("loaded %d packs, want all %d supported collections", len(packs), expected)
	}
	for _, pack := range packs {
		if len(pack.Levels) == 0 {
			t.Errorf("%s has no levels", pack.File)
		}
		for i, level := range pack.Levels {
			board := game.NewBoard(level)
			if got, want := len(board.Field), board.Dim.Row*board.Dim.Column; got != want {
				t.Errorf("%s level %d: field has %d cells, want %d", pack.Name, i+1, got, want)
			}
			playerCount := 0
			for _, cell := range board.Field {
				if cell.Player {
					playerCount++
				}
			}
			if playerCount != 1 {
				t.Errorf("%s level %d has %d players, want exactly one", pack.Name, i+1, playerCount)
			}
		}
	}
}

func TestParseAutogeneratedCollection(t *testing.T) {
	data, err := assets.LevelFiles.ReadFile("levels/Autogenerated.xsb")
	if err != nil {
		t.Fatal(err)
	}
	levels, err := level.ParseLevels(string(data))
	if err != nil {
		t.Fatal(err)
	}
	if len(levels) != 52 {
		t.Fatalf("parsed %d levels, want 52", len(levels))
	}
	for i, levelText := range levels {
		board := game.NewBoard(levelText)
		playerCount := 0
		for _, cell := range board.Field {
			if cell.Player {
				playerCount++
			}
		}
		if playerCount != 1 {
			t.Errorf("level %d has %d players, want exactly one", i+1, playerCount)
		}
	}
}

