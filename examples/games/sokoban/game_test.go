func TestSaveProgress(t *testing.T) {
	path := filepath.Join(t.TempDir(), "config", "sokoban-progress.json")
	want := level.SavedProgress{"simple.xsb": 2, "xsokoban.xsb": 7}
	if err := level.SaveProgress(path, want); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	var got level.SavedProgress
	if err := json.Unmarshal(data, &got); err != nil {
		t.Fatal(err)
	}
	for pack, wantLevel := range want {
		if got[pack] != wantLevel {
			t.Errorf("%s progress: got %d, want %d", pack, got[pack], wantLevel)
		}
	}
}

